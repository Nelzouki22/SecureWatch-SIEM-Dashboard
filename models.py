"""
Database models for SecureWatch SIEM Dashboard.

Defines all SQLAlchemy ORM models: User, Event, Alert, Incident, AuditLog, Setting.
"""

# Standard library imports
from datetime import datetime

# Third-party imports
from flask_login import UserMixin
from werkzeug.security import check_password_hash, generate_password_hash

# First-party imports
from database import db

SEVERITIES = ("Information", "Warning", "Medium", "High", "Critical")
STATUSES = ("Open", "Investigating", "Resolved", "Closed")


class User(UserMixin, db.Model):
    """User account model for authentication and authorization."""

    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(64), unique=True, nullable=False, index=True)
    email = db.Column(db.String(120), unique=True, nullable=False)
    password_hash = db.Column(db.String(255), nullable=False)
    role = db.Column(db.String(20), default="analyst")
    is_active_flag = db.Column(db.Boolean, default=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    last_login = db.Column(db.DateTime)

    def set_password(self, pw: str) -> None:
        """Hash and store the user's password."""
        self.password_hash = generate_password_hash(pw)

    def check_password(self, pw: str) -> bool:
        """Verify a password against the stored hash."""
        return check_password_hash(self.password_hash, pw)

    @property
    def is_active(self) -> bool:
        """Return whether the user account is active."""
        return self.is_active_flag

    def to_dict(self) -> dict:
        """Serialize the user to a dictionary."""
        return {
            "id": self.id,
            "username": self.username,
            "email": self.email,
            "role": self.role,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class Event(db.Model):
    """Security event model representing a normalized log entry."""

    __tablename__ = "events"

    id = db.Column(db.Integer, primary_key=True)
    event_id = db.Column(db.Integer, index=True)
    timestamp = db.Column(db.DateTime, index=True, default=datetime.utcnow)
    severity = db.Column(db.String(20), index=True)
    event_type = db.Column(db.String(64), index=True)
    username = db.Column(db.String(64), index=True)
    source_ip = db.Column(db.String(64), index=True)
    message = db.Column(db.Text)
    raw = db.Column(db.Text)
    log_source = db.Column(db.String(64))
    detected = db.Column(db.Boolean, default=False)
    detection_rule = db.Column(db.String(64))

    def to_dict(self) -> dict:
        """Serialize the event to a dictionary."""
        return {
            "id": self.id,
            "event_id": self.event_id,
            "timestamp": self.timestamp.isoformat() if self.timestamp else None,
            "severity": self.severity,
            "event_type": self.event_type,
            "username": self.username,
            "source_ip": self.source_ip,
            "message": self.message,
            "log_source": self.log_source,
        }


class Alert(db.Model):
    """Security alert model generated by the threat detection engine."""

    __tablename__ = "alerts"

    id = db.Column(db.Integer, primary_key=True)
    alert_type = db.Column(db.String(64), index=True)
    severity = db.Column(db.String(20), index=True)
    title = db.Column(db.String(120))
    description = db.Column(db.Text)
    source_ip = db.Column(db.String(64), index=True)
    username = db.Column(db.String(64))
    count = db.Column(db.Integer, default=1)
    status = db.Column(db.String(20), default="New")
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    def to_dict(self) -> dict:
        """Serialize the alert to a dictionary."""
        return {
            "id": self.id,
            "alert_type": self.alert_type,
            "severity": self.severity,
            "title": self.title,
            "description": self.description,
            "source_ip": self.source_ip,
            "username": self.username,
            "count": self.count,
            "status": self.status,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class Incident(db.Model):
    """Incident model for tracking security incidents through their lifecycle."""

    __tablename__ = "incidents"

    id = db.Column(db.Integer, primary_key=True)
    incident_id = db.Column(db.String(32), unique=True, index=True)
    title = db.Column(db.String(120), nullable=False)
    severity = db.Column(db.String(20), index=True)
    status = db.Column(db.String(20), default="Open", index=True)
    assigned_to = db.Column(db.String(64))
    description = db.Column(db.Text)
    notes = db.Column(db.Text)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    resolved_at = db.Column(db.DateTime)

    def to_dict(self) -> dict:
        """Serialize the incident to a dictionary."""
        return {
            "id": self.id,
            "incident_id": self.incident_id,
            "title": self.title,
            "severity": self.severity,
            "status": self.status,
            "assigned_to": self.assigned_to,
            "description": self.description,
            "notes": self.notes,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


class AuditLog(db.Model):
    """Audit log model for tracking user actions and system events."""

    __tablename__ = "audit_logs"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, default=datetime.utcnow, index=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), index=True)
    username = db.Column(db.String(64))
    action = db.Column(db.String(64), index=True)
    detail = db.Column(db.Text)
    ip_address = db.Column(db.String(64))
    user = db.relationship("User", backref=db.backref("audit_logs", lazy=True))

    def to_dict(self) -> dict:
        """Serialize the audit log entry to a dictionary."""
        return {
            "id": self.id,
            "timestamp": self.timestamp.isoformat() if self.timestamp else None,
            "username": self.username,
            "action": self.action,
            "detail": self.detail,
            "ip_address": self.ip_address,
        }


class Setting(db.Model):
    """Application and user settings model."""

    __tablename__ = "settings"

    id = db.Column(db.Integer, primary_key=True)
    key = db.Column(db.String(64), unique=True, nullable=False)
    value = db.Column(db.String(255))